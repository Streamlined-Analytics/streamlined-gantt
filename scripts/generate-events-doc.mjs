/**
 * Writes docs/events.md from the event catalogue (src/model/event-catalogue.js),
 * the single source of truth. `--check` exits non-zero when the file is stale,
 * which CI runs.
 */
import { readFile, writeFile } from "node:fs/promises";
import { EVENT_CATALOGUE } from "../src/model/event-catalogue.js";
import { isCancelable } from "../src/model/event-names.js";

const TARGET = new URL("../docs/events.md", import.meta.url);

/** @returns {string} */
export function renderEventsDoc() {
  const groups = [...new Set(EVENT_CATALOGUE.map((spec) => spec.group))];
  const sections = groups.map((group) => {
    const rows = EVENT_CATALOGUE.filter((spec) => spec.group === group).map(
      (spec) =>
        `| \`${spec.name}\` | ${isCancelable(spec.name) ? "yes" : ""} | ${spec.payload.map((key) => `\`${key}\``).join(", ")} | ${spec.description} |`,
    );
    return [
      `## ${group}`,
      "",
      "| Event | Cancelable | Payload | When |",
      "| --- | --- | --- | --- |",
      ...rows,
    ].join("\n");
  });
  return [
    "# Events",
    "",
    "<!-- Generated by scripts/generate-events-doc.mjs from src/model/event-catalogue.js. Do not edit. -->",
    "",
    "Listen with `gantt.on(name, handler)`, or on the host element for the bubbling DOM",
    "mirror `gantt:<name>` (the same event object is the `detail`). Cancelable `before-*` events",
    "accept `preventDefault()` and `waitUntil(promise)`; see [integration.md](integration.md).",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n");
}

const expected = renderEventsDoc();
if (process.argv.includes("--check")) {
  const current = await readFile(TARGET, "utf8").catch(() => "");
  if (current !== expected) {
    console.error("docs/events.md is out of date: run node scripts/generate-events-doc.mjs");
    process.exit(1);
  }
} else {
  await writeFile(TARGET, expected);
}
